def test_accounting_identities(pipeline_data):
    """Verifies that 98%+ of synthetic financial statements satisfy strict accounting identities."""
    df_fin = pipeline_data["fin_reports"]
    expense_cols = [
        "programme_expenses", "administrative_expenses", "fundraising_expenses",
        "employee_expenses", "consultancy_expenses", "material_expenses", "other_expenses"
    ]

    reconciled_exp = 0
    reconciled_surplus = 0
    total = len(df_fin)

    for _, row in df_fin.iterrows():
        tot_inc = float(row["total_income"])
        tot_exp = float(row["total_expenditure"])
        surplus = float(row["surplus_or_deficit"])

        items_sum = sum(float(row[c]) for c in expense_cols if not pd.isna(row[c]))
        if abs(tot_exp - items_sum) < 1.0:
            reconciled_exp += 1

        if abs(surplus - (tot_inc - tot_exp)) < 1.0:
            reconciled_surplus += 1

    assert (reconciled_exp / total) >= 0.98, f"Reconciliation rate too low: {reconciled_exp / total}"
    assert (reconciled_surplus / total) >= 0.98, f"Surplus reconciliation rate too low: {reconciled_surplus / total}"


