def test_json_output_schema_conformity(pipeline_data):
    """Verifies that every generated NGO assessment contains all required Section 47 fields."""
    assessments = pipeline_data["assessments"]
    required_keys = [
        "ngo_id", "ngo_name", "assessment_date", "assessment_type",
        "trustability_score", "score_interpretation", "data_confidence",
        "confidence_band", "dimension_scores", "financial_analysis",
        "evidence_summary", "positive_evidence", "negative_evidence",
        "statistical_findings", "missing_evidence", "uncertainty",
        "limitations", "methodology"
    ]

    for nid, asmnt in list(assessments.items())[:20]:
        for k in required_keys:
            assert k in asmnt, f"Missing key '{k}' in assessment for {nid}"
        assert isinstance(asmnt["dimension_scores"], dict)
        assert len(asmnt["dimension_scores"]) == 4
        assert isinstance(asmnt["limitations"], list)
        assert len(asmnt["limitations"]) >= 3
